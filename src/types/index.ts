export interface Product {
  id: string
  title: string
  subtitle: string | null
  description: string | null
  handle: string
  thumbnail: string | null
  /** Gallery in admin order; `alt` comes from metadata.image_alts (set in the "Productos web" form) */
  images: { id: string; url: string; alt: string }[]
  /** Lowest variant price ("desde" when there is more than one variant) */
  price: number
  currencyCode: string
  /** Cheapest variant; used for quick add */
  variantId: string | null
  sku: string | null
  /** All purchasable variants (e.g. sizes), cheapest first */
  variants: { id: string; title: string; sku: string | null; price: number; dimensions: string | null }[]
  /** Price is a starting price (several sizes) */
  priceFrom: boolean
  /** Commercial state chosen in the admin (default "on_order": KARVEN fabrica al confirmar) */
  availability: ProductAvailability
  /** The admin decided to show the reference price; otherwise the web offers "Solicitar cotización" only */
  showPrice: boolean
  /** Price already includes ITBMS */
  taxIncluded: boolean
  /** "Uso recomendado" */
  uses: string | null
  collection: { title: string; handle: string } | null
  /** Medusa product categories (child categories of the Karven tree, e.g. MED-01) */
  categories: { id: string; name: string; handle: string }[]
  /** Technical specs read from Medusa product metadata */
  material: string | null
  gauge: string | null
  finish: string | null
  dimensions: string | null
  /** Extra note shown next to the dimensions (e.g. "Bandeja removible 50 × 35 cm") */
  dimensionsNote: string | null
  capacity: string | null
  wheels: string | null
  options: string | null
  warranty: string | null
  color: string | null
  features: string[]
  badge: string | null
  /** Technical datasheet PDF uploaded from the Medusa admin (metadata.datasheet_url / datasheet_name) */
  datasheetUrl: string | null
  datasheetName: string | null
  /** SEO overrides from the admin (empty = generated by the page) */
  seoTitle: string | null
  seoDescription: string | null
  createdAt: string
}

export type ProductAvailability = "available" | "on_order" | "custom" | "unavailable"

export const AVAILABILITY_LABEL: Record<ProductAvailability, string> = {
  available: "Disponible",
  on_order: "Bajo pedido",
  custom: "Fabricación a medida",
  unavailable: "No disponible",
}

export interface Collection {
  id: string
  title: string
  handle: string
}
